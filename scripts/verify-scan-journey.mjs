import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(specifier,context,next){if(specifier==='./scan-auth-return') return next('./scan-auth-return.ts',context);return next(specifier,context);}});
globalThis.fetch=async()=>{throw new Error('External service calls forbidden');};
const {scanLimit,reportReturnHref,deeperScanAuthHref,authReturnHref,validPendingPlan}=await import('../src/lib/scan-journey.ts');
assert.deepEqual(scanLimit(403,'Credits exhausted'),{message:'Credits exhausted',rateLimited:false});
assert.deepEqual(scanLimit(429,'Hourly limit','3600'),{message:'Hourly limit',rateLimited:true,retryMinutes:60});
assert.deepEqual(scanLimit(429,'Hourly limit','invalid'),{message:'Hourly limit',rateLimited:true});
assert.equal(scanLimit(500,'Unavailable'),null);
assert.equal(scanLimit(400,'Invalid target'),null);
assert.equal(deeperScanAuthHref('owned-123'),'/register?scan=owned-123&intent=deeper');
assert.equal(deeperScanAuthHref('owned-123','login'),'/login?scan=owned-123&intent=deeper');
assert.equal(reportReturnHref('owned-123','deeper'),'/scan/owned-123?next=repo');
assert.equal(reportReturnHref('owned-123','https://evil.invalid'),'/scan/owned-123');
assert.equal(reportReturnHref('../bad','deeper'),'/dashboard');
assert.equal(authReturnHref('owned-123','deeper',null,'/dashboard'),'/scan/owned-123?next=repo');
assert.equal(authReturnHref('owned-123','deeper','starter','/dashboard'),'/pricing?checkout=starter#plans');
assert.equal(authReturnHref(null,null,'pro','/dashboard'),'/pricing?checkout=pro#plans');
assert.equal(authReturnHref(null,null,'invalid','/pricing'),'/pricing');
assert.equal(validPendingPlan('constructor'),null);
console.log('Scan journey: admission limits, auth intent, scan return and plan continuation passed.');
